def apply(source,before,after):
    pattern=r'\s*'.join(re.escape(char) for char in re.sub(r'\s+','',before))
    result,count=re.subn(pattern,lambda _:after,source)
    if count!=1:raise ValueError(f'expected one occurrence, found {count}: {before}')
    return result


